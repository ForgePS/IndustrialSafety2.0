CREATE OR REPLACE FUNCTION public.custom_access_token_hook(event jsonb) RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path TO 'public' AS $function$
declare claims jsonb;
user_roles varchar [];
user_permissions text [];
auth_user_id uuid;
begin -- Get user_id from the event
auth_user_id := (event->>'user_id')::uuid;
-- Get the existing claims
claims := event->'claims';
-- Get user's roles
select array_agg(r.role)
from public.users u
  join public.user_roles ur on u.id = ur.user_id
  join public.roles r on ur.role_id = r.id
where u.user_id = auth_user_id into user_roles;
-- Get user permissions
select array_agg(distinct p.permission)
from public.users u
  join public.user_roles ur on u.id = ur.user_id
  join public.role_permissions rp on ur.role_id = rp.role_id
  join public.permissions p on rp.permission_id = p.id
where u.user_id = auth_user_id into user_permissions;
-- Set default values if null
user_roles := coalesce(user_roles, array []::varchar []);
user_permissions := coalesce(user_permissions, array []::text []);
-- Set the claims
claims := claims || jsonb_build_object(
  'roles',
  user_roles,
  'permissions',
  user_permissions
);
-- Return the modified event
return jsonb_set(event, '{claims}', claims);
end;
$function$;
CREATE OR REPLACE FUNCTION public.get_user_hierarchy(target_user_id bigint) RETURNS smallint LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public' AS $function$
DECLARE user_hierarchy smallint;
BEGIN
SELECT MIN(r.hierarchy) INTO user_hierarchy
FROM roles r
  JOIN user_roles ur ON r.id = ur.role_id
WHERE ur.user_id = target_user_id;
RETURN COALESCE(user_hierarchy, 999);
END;
$function$;
CREATE OR REPLACE FUNCTION public.get_user_higher_hierarchy(user_id uuid) RETURNS integer LANGUAGE sql STABLE SECURITY DEFINER AS $function$
SELECT COALESCE(MIN(r.hierarchy), 999) -- Return high number if no roles found
FROM public.user_roles ur
  JOIN public.roles r ON r.id = ur.role_id
WHERE ur.user_id = user_id;
$function$;
CREATE OR REPLACE FUNCTION public.get_user_id_from_auth(auth_uid uuid) RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER
SET search_path TO 'public' AS $function$
SELECT id
FROM users
WHERE user_id = auth_uid;
$function$;
