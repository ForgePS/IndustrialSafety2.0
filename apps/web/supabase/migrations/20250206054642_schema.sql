CREATE OR REPLACE FUNCTION public.admin_only() RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER AS $function$ BEGIN IF get_user_hierarchy(get_user_id_from_auth(auth.uid())) = 1 THEN RETURN true;
END IF;
RAISE EXCEPTION 'Only admin can perform this action';
END;
$function$;
CREATE OR REPLACE FUNCTION public.can_manage_role(role_hierarchy integer) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER AS $function$
DECLARE user_hierarchy integer;
BEGIN -- Get user's hierarchy
user_hierarchy := get_user_hierarchy(get_user_id_from_auth(auth.uid()));
-- Check if user has required hierarchy level
IF user_hierarchy IS NULL THEN RAISE EXCEPTION 'User hierarchy not found';
END IF;
-- User can only manage roles with lower hierarchy
IF user_hierarchy = role_hierarchy THEN RAISE EXCEPTION 'You cannot modify roles at the same hierarchy level as yours';
END IF;
IF user_hierarchy > role_hierarchy THEN RAISE EXCEPTION 'You cannot modify roles above your hierarchy level';
END IF;
RETURN true;
END;
$function$;
CREATE OR REPLACE FUNCTION public.can_manage_user(auth_uid uuid, target_user_id uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER AS $function$
SELECT CASE
    -- Users can always manage themselves
    WHEN auth_uid = target_user_id THEN true -- Otherwise check hierarchy
    ELSE (
      SELECT get_user_higher_hierarchy(auth_uid) < get_user_higher_hierarchy(target_user_id)
    )
  END;
$function$;
CREATE OR REPLACE FUNCTION public.can_perform_user_action(auth_uid uuid, target_user_id bigint) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public' AS $function$
DECLARE requesting_user_id bigint;
requesting_hierarchy smallint;
target_hierarchy smallint;
BEGIN -- Get the requesting user's internal ID
requesting_user_id := get_user_id_from_auth(auth_uid);
-- Users cannot perform actions on themselves
IF requesting_user_id = target_user_id THEN RAISE EXCEPTION 'You cannot perform actions on yourself';
END IF;
-- Get hierarchies (using MIN to get the highest role - lowest number)
requesting_hierarchy := get_user_hierarchy(requesting_user_id);
target_hierarchy := get_user_hierarchy(target_user_id);
-- Check hierarchy levels - can only perform actions on users with lower hierarchy
IF requesting_hierarchy >= target_hierarchy THEN RAISE EXCEPTION 'You cannot perform actions on users with the same role level';
END IF;
RETURN true;
END;
$function$;
CREATE OR REPLACE FUNCTION public.can_update_permission(p_id bigint) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER AS $function$
DECLARE user_hierarchy smallint;
has_lower_hierarchy boolean;
BEGIN -- Get user's hierarchy
user_hierarchy := get_user_hierarchy(get_user_id_from_auth(auth.uid()));
-- Admin can do anything
IF user_hierarchy = 1 THEN RETURN true;
END IF;
-- Check if this permission is assigned to any role with lower hierarchy than the user
SELECT EXISTS (
    SELECT 1
    FROM role_permissions rp
      JOIN roles r ON r.id = rp.role_id
    WHERE rp.permission_id = p_id
      AND r.hierarchy > user_hierarchy -- Lower level roles have higher hierarchy numbers
  ) INTO has_lower_hierarchy;
-- If permission is assigned to lower hierarchy roles OR not assigned to any role
IF has_lower_hierarchy
OR NOT EXISTS (
  SELECT 1
  FROM role_permissions rp
  WHERE rp.permission_id = p_id
) THEN -- Only then check if user has the required permission
RETURN true;
END IF;
-- Permission is only assigned to roles with same or higher hierarchy
RAISE EXCEPTION 'You cannot modify this permission as it is only assigned to roles with higher or same hierarchy level than yours (%).',
user_hierarchy;
END;
$function$;
CREATE OR REPLACE FUNCTION public.can_update_user(auth_uid uuid, target_user_id bigint) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public' AS $function$
DECLARE requesting_user_id bigint;
BEGIN -- Get the requesting user's internal ID
requesting_user_id := get_user_id_from_auth(auth_uid);
-- Users can always update themselves
IF requesting_user_id = target_user_id THEN RETURN true;
END IF;
-- For other users, check hierarchy and role restrictions
RETURN can_perform_user_action(auth_uid, target_user_id);
END;
$function$;
CREATE OR REPLACE FUNCTION public.can_view_user(auth_uid uuid, target_user_id bigint) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public' AS $function$
DECLARE requesting_user_id bigint;
requesting_hierarchy smallint;
target_hierarchy smallint;
BEGIN -- Get the requesting user's internal ID
requesting_user_id := get_user_id_from_auth(auth_uid);
-- Get hierarchies
requesting_hierarchy := get_user_hierarchy(requesting_user_id);
target_hierarchy := get_user_hierarchy(target_user_id);
-- Users can:
-- 1. Always view themselves
-- 2. View users with equal or lower hierarchy
RETURN requesting_user_id = target_user_id
OR requesting_hierarchy <= target_hierarchy;
END;
$function$;
CREATE OR REPLACE FUNCTION public.check_role_hierarchy(auth_uid uuid, target_user_id bigint) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public' AS $function$
DECLARE requesting_user_id bigint;
requesting_hierarchy smallint;
target_hierarchy smallint;
BEGIN -- Get the requesting user's internal ID
requesting_user_id := get_user_id_from_auth(auth_uid);
-- Get hierarchies
requesting_hierarchy := get_user_hierarchy(requesting_user_id);
target_hierarchy := get_user_hierarchy(target_user_id);
-- Return true if requesting user has higher or equal hierarchy (lower number)
